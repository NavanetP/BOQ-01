interface DynamicIconProps extends IconProps {
  name: string;
}

export const Icon = ({ name, size = 18, ...props }: DynamicIconProps) => {
  const Comp = ICON_MAP[name];
  if (!Comp) {
    // Fallback: render a simple box icon
    return (
      <svg
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth="2"
        strokeLinecap="round"
        strokeLinejoin="round"
        {...props}
      >
        <rect x="3" y="3" width="18" height="18" rx="2" ry="2" />
      </svg>
    );
  }
  return <Comp size={size} {...props} />;
};
